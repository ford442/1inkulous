//
// Reads the flat C ABI out of cpp/include/1inkulous/core_abi.h and renders the
// TypeScript declaration of it. core_abi.h is the one place the ABI is written:
// src/wasm/core-abi.d.ts is generated from it (`npm run gen:abi`) and
// `npm run test:abi` fails when the two have drifted apart.
//
// The header is plain C: one declaration per `;`, scalar and pointer types only,
// and the `//` block directly above a declaration documents it. This parser
// supports exactly that and refuses anything else, so a type it does not know
// is an error here rather than a quietly wrong `number` in the typings.

import { readFileSync } from 'node:fs'

export const HEADER = 'cpp/include/1inkulous/core_abi.h'
export const GENERATED = 'src/wasm/core-abi.d.ts'

const root = new URL('../', import.meta.url)
export const read = (path) => readFileSync(new URL(path, root), 'utf8')

/** C type -> what the value is on the JavaScript side. */
const SCALARS = new Set(['int', 'double', 'float'])

/** `core_nav_alloc` -> `nav_alloc`, and `planet_radius` -> `planetRadius`. */
const camel = (name) => name.replace(/_(\w)/g, (_, c) => c.toUpperCase())

function jsType(cType, where) {
  const type = cType.replace(/\bconst\b/g, '').replace(/\s+/g, ' ').trim()
  if (type === 'void') return 'void'
  if (SCALARS.has(type)) return 'number'
  // Every pointer crosses the boundary as a byte offset into linear memory.
  if (/^(int|float|char) ?\*$/.test(type)) return 'Ptr'
  throw new Error(`${HEADER}: ${where}: no TypeScript type for C type "${cType.trim()}"`)
}

/**
 * Every function the header declares, in order:
 * `{ name, returns, params: [{ name, type }], doc }`, where `doc` is the comment
 * block immediately above it (empty when there is none).
 */
export function parseHeader(source = read(HEADER)) {
  const functions = []
  let comment = []
  let pending = null

  for (const line of source.split('\n')) {
    const trimmed = line.trim()

    if (pending !== null) {
      pending.text += ` ${trimmed}`
      if (trimmed.includes(';')) {
        functions.push(declaration(pending.text, pending.doc))
        pending = null
      }
      continue
    }

    if (trimmed.startsWith('//')) {
      comment.push(trimmed.replace(/^\/\/ ?/, ''))
      continue
    }

    if (/^[A-Za-z_][\w\s*]*\bcore_\w+\s*\(/.test(trimmed)) {
      const doc = comment.join('\n').trim()
      comment = []
      if (trimmed.includes(';')) functions.push(declaration(trimmed, doc))
      else pending = { text: trimmed, doc }
      continue
    }

    // A blank line, a directive, `extern "C" {`: the comment above belonged to
    // something else.
    comment = []
  }
  if (pending !== null) throw new Error(`${HEADER}: unterminated declaration: ${pending.text}`)
  return functions
}

function declaration(text, doc) {
  const match = /^([A-Za-z_][\w\s*]*?)\b(core_\w+)\s*\(([^)]*)\)\s*;/.exec(text)
  if (!match) throw new Error(`${HEADER}: cannot parse declaration: ${text}`)
  const [, returnType, name, list] = match
  const params = []
  const trimmed = list.trim()
  if (trimmed !== '' && trimmed !== 'void') {
    for (const part of trimmed.split(',')) {
      const parameter = /^(.*?)([A-Za-z_]\w*)$/.exec(part.trim())
      if (!parameter?.[1]?.trim()) {
        throw new Error(`${HEADER}: ${name}: unnamed or unparsable parameter "${part.trim()}"`)
      }
      params.push({ name: camel(parameter[2]), type: jsType(parameter[1], `${name}(${part.trim()})`) })
    }
  }
  return { name, returns: jsType(returnType, name), params, doc }
}

function jsdoc(doc, indent) {
  if (doc === '') return ''
  const lines = doc.replace(/\*\//g, '* /').split('\n')
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`
}

/** The text of src/wasm/core-abi.d.ts. */
export function render(functions = parseHeader()) {
  let out = `// GENERATED by scripts/gen-abi.mjs from ${HEADER} — do not edit.
// Change the C declaration and run \`npm run gen:abi\`; \`npm run test:abi\` fails
// while this file and the header disagree.
//
// Each member is an exported C function, called as \`module._core_*\`. Use the
// wrapper in src/sim/simulation.ts rather than reaching for these directly.

/**
 * A byte offset into the module's linear memory. Every pointer the C ABI returns
 * or takes is one: read it through HEAPU8 / HEAP32 / HEAPF32 / HEAPF64 (see
 * CoreModule in core.d.ts), and re-read it after anything that can grow memory.
 */
export type Ptr = number

export type CoreExports = {
`
  for (const fn of functions) {
    out += jsdoc(fn.doc, '  ')
    const params = fn.params.map((p) => `${p.name}: ${p.type}`)
    const inline = `  _${fn.name}: (${params.join(', ')}) => ${fn.returns}`
    if (inline.length <= 100) {
      out += `${inline}\n`
    } else {
      out += `  _${fn.name}: (\n${params.map((p) => `    ${p},`).join('\n')}\n  ) => ${fn.returns}\n`
    }
  }
  return `${out}}\n`
}
