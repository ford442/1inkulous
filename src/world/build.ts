/**
 * Builds a scenario onto the core: the one place a world is laid out.
 *
 * In a fixed order, every time — the order is part of what a world *is*:
 *
 *   1. the match seed
 *   2. the planet mesh and the ground: generated by the core from a seed, or
 *      the scenario's own height of every node, or flat
 *   3. every tribe's home: where the scenario says, or for "auto" the
 *      flattest inland ground at least `placement.apart` from the homes
 *      before it — on the first village's landmass (the largest, for the
 *      first), or with `placement.separate` on a landmass of its own
 *   4. every tribe's huts, each on a pad levelled for it (unless the ground
 *      is given exactly, when it is taken as it is)
 *   5. the forest: the scatter, then the listed trees, then each village
 *      topped up to `groves` trees nearby
 *   6. every tribe's people: the shaman at the heart, then braves and
 *      warriors spread round home over walkable ground, then those placed
 *      by hand
 *   7. each tribe's wood, mana, spell unlocks and AI personality
 *   8. the match seed again, so the match starts from the same random state
 *      however the world was built (scattered or listed trees draw
 *      differently)
 *   9. in play, the AI switched on for every tribe it plays
 *
 * Every direction the builder works out for itself is rounded to six
 * places before it is used, and `baked` is the scenario again with all of
 * them written in: every home, hut, person and tree where it ended up, and
 * nothing left to "auto" or to chance. Building `baked` gives the same world
 * as building the scenario, to the bit — the same state hash — which is what
 * lets the editor work on an explicit document without changing the world.
 */

export type BuildMode = 'play' | 'edit'

export type BuildOptions = {
  /** 'play' (default) hands the AI its tribes; 'edit' leaves the world still. */
  mode?: BuildMode
  /** Hand every tribe to the AI, the player's too: for tests and demos. */
  allAi?: boolean
}

export type BuiltTribe = {
  readonly tribe: number
  readonly name: string
  readonly control: TribeSpec['control']
  /** Where the village grew from; null when nowhere on the planet would take it. */
  readonly home: Vec3 | null
  /** The AI's personality, as the HUD names it; null for a tribe it does not play. */
  readonly personality: string | null
}

export type Populated = {
  readonly tribes: readonly BuiltTribe[]
  /** The scenario with everything the builder decided written in. */
  readonly baked: Scenario
  /** What could not be built as asked: a hut on no ground, a tree in the sea. */
  readonly problems: readonly string[]
}

export type World = Populated & {
  readonly scenario: Scenario
  readonly planet: Planet
  readonly terrain: Terrain
}

/** Blue, red, yellow, green: the four colour slots the core keeps tribes in. */
export const TRIBE_NAMES: readonly string[] = ['Blue', 'Red', 'Yellow', 'Green']

/** A tribe's name as the HUD shows it: its scenario name, else its colour. */
export const tribeName = (spec: Pick<TribeSpec, 'tribe' | 'name'>): string =>
  spec.name ?? TRIBE_NAMES[spec.tribe] ?? `Tribe ${spec.tribe}`

/** Radians between homes placed "auto" when the scenario does not say. */
const APART_TWO = 1.2
const APART_MORE = 0.9
/** A village's grove: trees counted within this many radians of home. */
const GROVE_ANGLE = 0.3
/** Candidates tried for a walking route from the first home. */
const ROUTE_TRIES = 40
/** Huts after the first stand on rings this far round home, nearest first. */
const HUT_RINGS = [0.22, 0.3, 0.38]
/** A pad is levelled this many times the hut's footprint across: all of it, and no further. */
const PAD_SCALE = 1.8
/** Placing is never refused for wood; the tribe's real stock is set after. */
const BUILDING_WOOD = 1_000_000

const SPELL_IDS: Readonly<Record<SpellKey, Spell>> = {
  landBridge: Spell.landBridge,
  blast: Spell.blast,
  flatten: Spell.flatten,
  swamp: Spell.swamp,
}

// --- vectors ------------------------------------------------------------------

/** Six places, and never -0: what the builder hands the core and writes back out. */
const round = (x: number) => Math.round(x * 1e6) / 1e6 || 0
export const roundVec = (v: readonly number[]): Vec3 => [round(v[0]!), round(v[1]!), round(v[2]!)]
const unit = (v: readonly number[]): Vec3 => normalize([v[0]!, v[1]!, v[2]!])
const dot = (a: Vec3, b: Vec3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
const angleBetween = (a: Vec3, b: Vec3) => Math.acos(Math.max(-1, Math.min(1, dot(unit(a), unit(b)))))

function nodeDirection(graph: NavGraph, node: number): Vec3 {
  const d = graph.directions
  return unit([d[node * 3]!, d[node * 3 + 1]!, d[node * 3 + 2]!])
}

/** The node nearest a direction, walkable or not. */
function nearestNode(graph: NavGraph, direction: Vec3): number {
  const at = unit(direction)
  let best = -1
  let bestDot = -Infinity
  for (let node = 0; node < graph.nodeCount; node += 1) {
    const d = graph.directions
    const along = d[node * 3]! * at[0] + d[node * 3 + 1]! * at[1] + d[node * 3 + 2]! * at[2]
    if (along > bestDot) {
      bestDot = along
      best = node
    }
  }
  return best
}

/** The tangent at `from` towards `to`, or any tangent if they coincide. */
function tangentTowards(from: Vec3, to: Vec3 | null): Vec3 {
  if (to) {
    const along = dot(to, from)
    const t: Vec3 = [to[0] - from[0] * along, to[1] - from[1] * along, to[2] - from[2] * along]
    if (Math.hypot(...t) > 1e-9) {
      return normalize(t)
    }
  }
  const helper: Vec3 = Math.abs(from[1]) < 0.9 ? [0, 1, 0] : [1, 0, 0]
  const along = dot(helper, from)
  return normalize([helper[0] - from[0] * along, helper[1] - from[1] * along, helper[2] - from[2] * along])
}

/** `from` carried `distance` radians along the surface, `bearing` radians round from `toward`. */
function around(from: Vec3, toward: Vec3, distance: number, bearing: number): Vec3 {
  const side: Vec3 = [
    from[1] * toward[2] - from[2] * toward[1],
    from[2] * toward[0] - from[0] * toward[2],
    from[0] * toward[1] - from[1] * toward[0],
  ]
  const c = Math.cos(bearing)
  const s = Math.sin(bearing)
  const t: Vec3 = [toward[0] * c + side[0] * s, toward[1] * c + side[1] * s, toward[2] * c + side[2] * s]
  return normalize([
    from[0] * Math.cos(distance) + t[0] * Math.sin(distance),
    from[1] * Math.cos(distance) + t[1] * Math.sin(distance),
    from[2] * Math.cos(distance) + t[2] * Math.sin(distance),
  ])
}

// --- the ground ---------------------------------------------------------------

/** A generated terrain spec as the core's generator takes it. */
export function worldGenParams(spec: Extract<TerrainSpec, { kind: 'generated' }>): WorldGenParams {
  const { kind: _kind, ...params } = spec
  // Absent fields are left out, not set to undefined: the core's defaults fill them.
  return Object.fromEntries(Object.entries(params).filter(([, value]) => value !== undefined)) as WorldGenParams
}

/** The ground a flat or height-field terrain spec stands for, one height per node. */
function groundHeights(spec: TerrainSpec, nodeCount: number): Float32Array | null {
  if (spec.kind === 'heights') {
    return decodeHeightField(spec.data)
  }
  if (spec.kind === 'flat') {
    return new Float32Array(nodeCount).fill(spec.height ?? 0)
  }
  return null
}

function terrainOptions(scenario: Scenario): TerrainOptions {
  const spec = scenario.planet.terrain
  if (spec.kind === 'generated') {
    return { generate: worldGenParams(spec) }
  }
  return { heights: groundHeights(spec, nodeCountFor(scenario.planet.resolution))! }
}

/** Puts a scenario's ground back on a core that already has its planet: the editor's rebuild. */
export function restoreGround(simulation: Simulation, scenario: Scenario, nodeCount: number): void {
  const spec = scenario.planet.terrain
  if (spec.kind === 'generated') {
    simulation.generateTerrain(worldGenParams(spec))
  } else {
    simulation.setTerrainHeights(groundHeights(spec, nodeCount)!)
  }
}

/**
 * Dry nodes two links in from any water, so a hut's footprint and the ring
 * under its walls are on land, ranked flattest first.
 */
function inlandByFlatness(graph: NavGraph, heights: Float32Array, planetRadius: number): number[] {
  const { nodeCount, neighborOffsets, neighbors } = graph
  const dryAround = (node: number) => {
    for (let link = neighborOffsets[node]!; link < neighborOffsets[node + 1]!; link += 1) {
      if (heights[neighbors[link]!]! <= 0) {
        return false
      }
    }
    return true
  }
  const scored: { node: number; slope: number }[] = []
  for (let node = 0; node < nodeCount; node += 1) {
    if (heights[node]! <= 0 || !dryAround(node)) {
      continue
    }
    let inland = true
    let slope = 0
    const here = nodeDirection(graph, node)
    for (let link = neighborOffsets[node]!; link < neighborOffsets[node + 1]!; link += 1) {
      const next = neighbors[link]!
      if (!dryAround(next)) {
        inland = false
        break
      }
      const run = angleBetween(here, nodeDirection(graph, next)) * planetRadius
      if (run > 0) {
        slope = Math.max(slope, Math.abs(heights[next]! - heights[node]!) / run)
      }
    }
    if (inland && slope <= MAX_WALKABLE_SLOPE) {
      scored.push({ node, slope })
    }
  }
  // Stable: equal slopes keep node order, so the ranking is the same every time.
  scored.sort((a, b) => a.slope - b.slope || a.node - b.node)
  return scored.map((entry) => entry.node)
}

/**
 * Every node's landmass — the dry ground connected to it by steps a follower
 * could take — numbered largest first; -1 for water.
 */
function landmasses(graph: NavGraph, heights: Float32Array, planetRadius: number): Int32Array {
  const { nodeCount, neighborOffsets, neighbors } = graph
  const raw = new Int32Array(nodeCount).fill(-1)
  const sizes: number[] = []
  for (let start = 0; start < nodeCount; start += 1) {
    if (heights[start]! <= 0 || raw[start]! >= 0) {
      continue
    }
    const id = sizes.length
    let size = 0
    const queue = [start]
    raw[start] = id
    while (queue.length > 0) {
      const node = queue.pop()!
      size += 1
      const here = nodeDirection(graph, node)
      for (let link = neighborOffsets[node]!; link < neighborOffsets[node + 1]!; link += 1) {
        const next = neighbors[link]!
        if (raw[next]! >= 0 || heights[next]! <= 0) {
          continue
        }
        const run = angleBetween(here, nodeDirection(graph, next)) * planetRadius
        if (run > 0 && Math.abs(heights[next]! - heights[node]!) / run > MAX_WALKABLE_SLOPE) {
          continue
        }
        raw[next] = id
        queue.push(next)
      }
    }
    sizes.push(size)
  }
  // Renumbered by size, largest 0; ties by discovery, so it is the same every time.
  const order = sizes.map((size, id) => ({ size, id })).sort((a, b) => b.size - a.size || a.id - b.id)
  const rank = new Int32Array(sizes.length)
  order.forEach((entry, i) => (rank[entry.id] = i))
  return raw.map((id) => (id < 0 ? -1 : rank[id]!))
}

function resolveHomes(simulation: Simulation, terrain: Terrain, scenario: Scenario): (Vec3 | null)[] {
  const { graph, planet } = terrain
  // A home the scenario gives is used as given; only the ones worked out here
  // are rounded. Either way the value is what gets written back out, so a
  // baked world hands the core exactly the numbers the original did.
  const homes: (Vec3 | null)[] = scenario.tribes.map((tribe) =>
    tribe.home !== undefined && tribe.home !== 'auto' ? [...tribe.home] : null,
  )
  const auto = scenario.tribes.map((tribe) => tribe.home === undefined || tribe.home === 'auto')
  if (!auto.some(Boolean)) {
    return homes
  }
  const heights = terrain.heights()
  const candidates = inlandByFlatness(graph, heights, planet.radius)
  const landmass = landmasses(graph, heights, planet.radius)
  const placement = scenario.rules?.placement
  const wantApart = placement?.apart ?? (scenario.tribes.length <= 2 ? APART_TWO : APART_MORE)
  const separate = placement?.separate ?? false
  const together = !separate && (placement?.walkable ?? true)
  const landmassOf = (home: Vec3) => landmass[nearestNode(graph, home)] ?? -1

  scenario.tribes.forEach((_tribe, i) => {
    if (!auto[i] || candidates.length === 0) {
      return
    }
    const placed = homes.filter((home): home is Vec3 => home !== null)
    let pool = candidates
    if (separate) {
      // A landmass of its own, the largest left first.
      const taken = new Set(placed.map(landmassOf))
      const free = candidates.filter((node) => !taken.has(landmass[node]!))
      pool = (free.length > 0 ? free : candidates)
        .map((node, order) => ({ node, order }))
        .sort((a, b) => landmass[a.node]! - landmass[b.node]! || a.order - b.order)
        .map((entry) => entry.node)
    } else if (together) {
      // The same landmass as the first village, or the largest there is.
      const target = placed.length > 0 ? landmassOf(placed[0]!) : 0
      const same = candidates.filter((node) => landmass[node] === target)
      pool = same.length > 0 ? same : candidates
    }
    // Relaxed a quarter at a time if nowhere is that far from everyone.
    for (let apart = wantApart, tries = 0; tries < 8; apart *= 0.75, tries += 1) {
      const far = pool.filter((node) =>
        placed.every((home) => angleBetween(nodeDirection(graph, node), home) >= apart),
      )
      if (far.length === 0) {
        continue
      }
      // The landmass is a cheap first cut; a route the core would really
      // walk is the proof, and the flattest site with one is taken.
      const first = placed[0]
      const routed =
        together && first
          ? far
              .slice(0, ROUTE_TRIES)
              .find((node) => simulation.module._core_nav_route(...first, ...nodeDirection(graph, node), 0) >= 0)
          : undefined
      homes[i] = roundVec(nodeDirection(graph, routed ?? far[0]!))
      return
    }
  })
  return homes
}

// --- the builder --------------------------------------------------------------

/** A spell's unlock as the core takes it: 0 now, -1 never, or a population. */
export function unlockAt(spec: UnlockSpec | undefined): number {
  return spec === undefined || spec === 'now' ? 0 : spec === 'never' ? SPELL_NEVER : spec
}

/** Builds `scenario` on a fresh core: the planet, the ground and everything on it. */
export function buildWorld(simulation: Simulation, scenario: Scenario, options: BuildOptions = {}): World {
  simulation.seedMatch(scenario.seed)
  const radius = scenario.planet.radius ?? 1
  const planet = createPlanet({
    resolution: scenario.planet.resolution,
    radius,
    maxHeight: scenario.planet.maxHeight ?? radius * 0.06,
    // Sea level everywhere: the ground comes from the scenario, through the core.
    terrain: 'flat',
  })
  const terrain = createTerrain(planet, simulation, terrainOptions(scenario))
  return { scenario, planet, terrain, ...populate(simulation, terrain, scenario, options) }
}

/**
 * Builds `scenario` again on the core `terrain` already stands on, over
 * whatever was there: the ground put back, everything else cleared and laid
 * out afresh. The planet must be the same size. What the editor does after
 * every change, so what it shows is always what the file will load as.
 */
export function rebuildWorld(
  simulation: Simulation,
  terrain: Terrain,
  scenario: Scenario,
  options: BuildOptions = {},
): Populated {
  if (nodeCountFor(scenario.planet.resolution) !== terrain.graph.nodeCount) {
    throw new Error('rebuildWorld needs a planet of the same resolution; build a new world instead.')
  }
  simulation.clearWorld()
  simulation.seedMatch(scenario.seed)
  restoreGround(simulation, scenario, terrain.graph.nodeCount)
  return populate(simulation, terrain, scenario, options)
}

function populate(
  simulation: Simulation,
  terrain: Terrain,
  scenario: Scenario,
  options: BuildOptions,
): Populated {
  const { graph, planet } = terrain
  const mode = options.mode ?? 'play'
  const problems: string[] = []
  const levelPads = scenario.planet.terrain.kind !== 'heights'

  // 3. Homes, judged on the ground before any pad is levelled.
  const homes = resolveHomes(simulation, terrain, scenario)

  // 4. Huts. A site is judged before anything is levelled, so one that is
  // passed over leaves the ground as it was: only a hut that goes up (or an
  // explicit one the author asked for) ever flattens a pad, and that is what
  // `baked` writes down.
  const footprints: { at: Vec3; angle: number }[] = []
  const bakedHuts: HutSpec[][] = scenario.tribes.map(() => [])
  const padOf = (footprint: number) => footprint * PAD_SCALE
  const usable = (at: Vec3, kind: HutKind, tribe: number) => {
    const report = simulation.hutSite(at, kind, tribe)
    if (!(report.site === HutSite.ok || (levelPads && report.site === HutSite.uneven)) || terrain.heightAt(at) <= 0) {
      return false
    }
    // Its pad must not drag the ground from under a hut already standing.
    return footprints.every((other) => angleBetween(at, other.at) > padOf(report.footprint) + other.angle * 1.5)
  }
  scenario.tribes.forEach((tribe, i) => {
    const home = homes[i] ?? null
    const huts = tribe.huts ?? []
    if (huts.length === 0) {
      return
    }
    simulation.setWood(tribe.tribe, BUILDING_WOOD)
    // The first faces the nearest other village, like a gate; the rest face home.
    const others = homes.filter((other, j): other is Vec3 => j !== i && other !== null)
    const nearest = home
      ? (others.sort((a, b) => angleBetween(a, home) - angleBetween(b, home))[0] ?? null)
      : null
    huts.forEach((hut, k) => {
      const kind = hut.kind === 'training' ? HutKind.training : HutKind.dwelling
      // As given, or worked out and rounded once: see resolveHomes.
      let at: Vec3 | null = null
      if (hut.at) {
        at = usable(hut.at, kind, tribe.tribe) ? [...hut.at] : null
      } else if (home) {
        const centre = unit(home)
        const toward = tangentTowards(centre, nearest)
        const sites: Vec3[] = k === 0 ? [home] : []
        for (const ring of HUT_RINGS) {
          for (let turn = 0; turn < 6; turn += 1) {
            sites.push(roundVec(around(centre, toward, ring, ((k - 1 + turn) * Math.PI) / 3)))
          }
        }
        at = sites.find((site) => usable(site, kind, tribe.tribe)) ?? null
      }
      if (!at) {
        const where = hut.at ? `at [${hut.at.join(', ')}]` : home ? 'round its home' : 'with no home'
        problems.push(`${tribeName(tribe)}: nowhere ${where} would take its ${hut.kind}`)
        return
      }
      const door: Vec3 = hut.door
        ? [...hut.door]
        : roundVec(tangentTowards(unit(at), k === 0 || !home ? nearest : unit(home)))
      const footprint = simulation.hutSite(at).footprint
      if (levelPads) {
        terrain.flatten(at, padOf(footprint), terrain.heightAt(at), 1)
      }
      // Kept even if it fails now: its pad was levelled, and a baked world
      // has to level it too to be the same world.
      bakedHuts[i]!.push({ kind: hut.kind, at, door })
      if (simulation.placeHut(at, door, tribe.tribe, kind) < 0) {
        problems.push(`${tribeName(tribe)}: the ${hut.kind} at [${at.join(', ')}] would not stand on its pad`)
        return
      }
      footprints.push({ at, angle: footprint })
    })
  })
  const onAPad = (node: number) => {
    const at = nodeDirection(graph, node)
    return footprints.some((pad) => angleBetween(at, pad.at) <= pad.angle * 1.05)
  }

  // 5. The forest.
  const trees = scenario.trees
  if ((trees?.scatter ?? 0) > 0) {
    simulation.spawnTrees(trees!.scatter!)
  }
  for (const tree of trees?.at ?? []) {
    const at = [tree[0]!, tree[1]!, tree[2]!] as const
    if (simulation.plantTree([...at], tree[3] ?? 1, tree[4] ?? 0) < 0) {
      problems.push(`the tree at [${at.join(', ')}] has no dry ground to stand on`)
    }
  }
  const groves = trees?.groves ?? 0
  if (groves > 0) {
    homes.forEach((home) => {
      if (home) {
        plantGrove(simulation, terrain, home, groves, onAPad)
      }
    })
  }

  // 6. People.
  const bakedUnits: UnitSpec[][] = scenario.tribes.map(() => [])
  scenario.tribes.forEach((tribe, i) => {
    const home = homes[i] ?? null
    const roles: UnitSpec['role'][] = [
      ...((tribe.shaman ?? true) ? (['shaman'] as const) : []),
      ...Array.from({ length: tribe.braves ?? 0 }, () => 'brave' as const),
      ...Array.from({ length: tribe.warriors ?? 0 }, () => 'warrior' as const),
    ]
    const placed: UnitSpec[] = []
    if (roles.length > 0) {
      if (!home) {
        problems.push(`${tribeName(tribe)}: nowhere on the planet would take its village`)
      } else {
        const nodes = findSpawnNodes(graph, terrain.heights(), planet.radius, roles.length, {
          start: nearestNode(graph, home),
          skip: onAPad,
        })
        nodes.forEach((node, k) => placed.push({ role: roles[k]!, at: roundVec(nodeDirection(graph, node)) }))
        if (nodes.length < roles.length) {
          problems.push(`${tribeName(tribe)}: room for ${nodes.length} of its ${roles.length} people`)
        }
      }
    }
    placed.push(...(tribe.units ?? []))
    for (const unitSpec of placed) {
      const at: Vec3 = [unitSpec.at[0], unitSpec.at[1], unitSpec.at[2]]
      const id =
        unitSpec.role === 'shaman'
          ? simulation.spawnShaman(at, tribe.tribe)
          : simulation.spawnFollower(at, tribe.tribe)
      if (id < 0) {
        problems.push(`${tribeName(tribe)}: the ${unitSpec.role} at [${at.join(', ')}] has nowhere to stand`)
        continue
      }
      if (unitSpec.role === 'warrior') {
        simulation.setFollowerRole(id, Role.warrior)
      }
      bakedUnits[i]!.push(unitSpec)
    }
  })

  // 7. Stores, spells and minds.
  scenario.tribes.forEach((tribe) => {
    simulation.setWood(tribe.tribe, tribe.wood ?? 0)
    simulation.setMana(tribe.tribe, tribe.mana ?? 0)
    for (const key of SPELL_KEYS) {
      const at = unlockAt(tribe.spells?.[key] ?? scenario.rules?.spells?.[key])
      if (at !== 0) {
        simulation.setSpellUnlock(tribe.tribe, SPELL_IDS[key], at)
      }
    }
    if (tribe.control === 'ai' || options.allAi) {
      simulation.configureAi(tribe.tribe, aiWeights(tribe.ai))
    }
  })

  // 8. The match starts from its seed, whatever the building drew.
  simulation.seedMatch(scenario.seed)

  // 9. The AI, in play.
  if (mode === 'play') {
    scenario.tribes.forEach((tribe) => {
      if (tribe.control === 'ai' || options.allAi) {
        simulation.enableAi(tribe.tribe)
      }
    })
  }

  const tribes: BuiltTribe[] = scenario.tribes.map((tribe, i) => ({
    tribe: tribe.tribe,
    name: tribeName(tribe),
    control: tribe.control,
    home: homes[i] ?? null,
    personality: tribe.control === 'ai' || options.allAi ? personalityLabel(tribe.ai) : null,
  }))
  for (const problem of problems) {
    console.warn(`[world] ${scenario.id}: ${problem}`)
  }
  return { tribes, baked: bake(simulation, scenario, homes, bakedHuts, bakedUnits), problems }
}

/** Tops a village's surroundings up to `wanted` trees, from the outside of the village in. */
function plantGrove(
  simulation: Simulation,
  terrain: Terrain,
  home: Vec3,
  wanted: number,
  onAPad: (node: number) => boolean,
) {
  const { graph, planet } = terrain
  const data = simulation.treeInstances()
  const stride = simulation.treeInstanceFloats
  let near = 0
  for (let id = 0; id < data.length / stride; id += 1) {
    const at: Vec3 = [data[id * stride]!, data[id * stride + 1]!, data[id * stride + 2]!]
    if (angleBetween(home, at) < GROVE_ANGLE) {
      near += 1
    }
  }
  if (near >= wanted) {
    return
  }
  const spread = findSpawnNodes(graph, terrain.heights(), planet.radius, 40, {
    start: nearestNode(graph, home),
    skip: onAPad,
  })
  for (let i = spread.length - 1; i >= 0 && near < wanted; i -= 2) {
    if (simulation.plantTree(roundVec(nodeDirection(graph, spread[i]!))) >= 0) {
      near += 1
    }
  }
}

/** The scenario with every decision the builder made written in. */
function bake(
  simulation: Simulation,
  scenario: Scenario,
  homes: readonly (Vec3 | null)[],
  huts: readonly HutSpec[][],
  units: readonly UnitSpec[][],
): Scenario {
  const data = simulation.treeInstances()
  const stride = simulation.treeInstanceFloats
  const trees: TreeSpec[] = []
  for (let id = 0; id < data.length / stride; id += 1) {
    const at = roundVec(unit([data[id * stride]!, data[id * stride + 1]!, data[id * stride + 2]!]))
    trees.push([...at, simulation.treeSize(id), simulation.treeTurn(id)])
  }
  const tribes: TribeSpec[] = scenario.tribes.map((tribe, i) => {
    const { braves: _braves, warriors: _warriors, units: _units, huts: _huts, home: _home, shaman: _shaman, ...rest } = tribe
    const home = homes[i]
    return {
      ...rest,
      home: home ?? 'auto',
      shaman: false,
      ...(units[i]!.length > 0 ? { units: units[i]! } : {}),
      ...(huts[i]!.length > 0 ? { huts: huts[i]! } : {}),
    }
  })
  const { trees: _trees, tribes: _tribes, ...rest } = scenario
  return { ...rest, ...(trees.length > 0 ? { trees: { at: trees } } : {}), tribes }
}
